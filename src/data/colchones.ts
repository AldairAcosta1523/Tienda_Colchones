type Definicion = {
  slug: string;
  /** Código corto para el SKU (3–4 letras). */
  codigo: string;
  nombre: string;
  coleccion: ColeccionId;
  construccion: Construccion;
  firmeza: Firmeza;
  altura: number;
  resumen: string;
  descripcion: string;
  /** Precio de la medida más pequeña ofrecida; las demás suben por `escala`. */
  desde: number;
  /** Medidas ofrecidas, de menor a mayor. */
  medidas: MedidaId[];
  /** Stock por medida; lo que falte se considera 0 (agotada). */
  stock: Partial<Record<MedidaId, number>>;
  nucleo: string;
  acogida: string;
  tejido: string;
  postura: string;
  recomendado: string;
  beneficios: string[];
  imagen: { src: string; alt: string };
  imagenHover?: { src: string; alt: string };
  destacado?: boolean;
  orden: number;
};

/** Incremento de precio por medida respecto a la más pequeña ofrecida. */
const ESCALA: Record<MedidaId, number> = { "090": 0, "120": 0, "140": 300, "160": 600, "180": 1000, "200": 1400 };

function variantes(d: Definicion): Variante[] {
  const base = ESCALA[d.medidas[0]];
  return d.medidas.map((id) => ({
    id,
    nombre: MEDIDAS[id].nombre,
    sku: `ALM-${d.codigo}-${id}`,
    medida: textoMedida(id),
    dimensiones: { ancho: MEDIDAS[id].ancho, largo: MEDIDAS[id].largo, alto: d.altura },
    precio: d.desde + ESCALA[id] - base,
    stock: d.stock[id] ?? 0,
  }));
}

function colchon(d: Definicion): Producto {
  return {
    slug: d.slug,
    nombre: d.nombre,
    categoria: "colchones",
    coleccion: d.coleccion,
    construccion: d.construccion,
    resumen: d.resumen,
    descripcion: d.descripcion,
    firmeza: d.firmeza,
    altura: `${d.altura} cm`,
    imagen: d.imagen,
    imagenHover: d.imagenHover,
    variantes: variantes(d),
    beneficios: d.beneficios,
    especificaciones: [
      { k: "Construcción", v: NOMBRE_CONSTRUCCION[d.construccion] },
      { k: "Firmeza", v: `${d.firmeza} (${NIVEL_FIRMEZA[d.firmeza]} de 5)` },
      { k: "Altura", v: `${d.altura} cm` },
      { k: "Núcleo", v: d.nucleo },
      { k: "Acogida", v: d.acogida },
      { k: "Tejido", v: d.tejido },
      { k: "Postura", v: d.postura },
      { k: "Recomendado", v: d.recomendado },
    ],
    orden: d.orden,
    destacado: d.destacado,
    demo: true,
  };
}

